-- SCRUM-22 is not yet present in this checkout. Keep the referenced identity
-- table minimal so a clean database can apply this migration; material fields
-- and its repository remain owned by that task.
CREATE TABLE IF NOT EXISTS material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY
);

CREATE TABLE movimentacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL,
    quantidade DECIMAL(19, 6) NOT NULL,
    tipo VARCHAR(20) NOT NULL,
    data_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ator VARCHAR(255),
    CONSTRAINT fk_movimentacao_material FOREIGN KEY (material_id) REFERENCES material(id),
    CONSTRAINT chk_movimentacao_quantidade_positiva CHECK (quantidade > 0),
    CONSTRAINT chk_movimentacao_tipo CHECK (tipo IN ('ENTRADA', 'CONSUMO', 'BAIXA', 'AJUSTE'))
);

CREATE INDEX idx_movimentacao_material_data_hora ON movimentacao(material_id, data_hora);
