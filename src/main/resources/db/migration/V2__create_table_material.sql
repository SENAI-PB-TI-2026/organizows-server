CREATE TABLE material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(255),
    categoria VARCHAR(50) NOT NULL,
    subgrupo VARCHAR(100),
    modelo VARCHAR(100),
    especificacoes_tecnicas VARCHAR(500),
    status VARCHAR(30) NOT NULL,
    quantidade_disponivel INT NOT NULL DEFAULT 0,
    quantidade_minima INT NOT NULL DEFAULT 0,
    localizacao_id BIGINT,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_material_codigo UNIQUE (codigo),
    CONSTRAINT fk_material_localizacao FOREIGN KEY (localizacao_id) REFERENCES localizacao(id),
    CONSTRAINT chk_material_quantidade_disponivel CHECK (quantidade_disponivel >= 0),
    CONSTRAINT chk_material_quantidade_minima CHECK (quantidade_minima >= 0)
);

CREATE INDEX idx_material_localizacao_id ON material(localizacao_id);
CREATE INDEX idx_material_codigo ON material(codigo);
CREATE INDEX idx_material_categoria ON material(categoria);
CREATE INDEX idx_material_status ON material(status);