-- A V1 da branch develop cria a tabela localizacao. Esta migration amplia o esquema.
CREATE TABLE material (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(50) NOT NULL,
    nome VARCHAR(150) NOT NULL,
    descricao VARCHAR(150) NOT NULL,
    caracteristicas VARCHAR(500),
    grupo VARCHAR(80) NOT NULL,
    subgrupo VARCHAR(80),
    categoria VARCHAR(50) NOT NULL,
    status VARCHAR(30) NOT NULL,
    localizacao_id BIGINT NOT NULL,
    criado_em TIMESTAMP NOT NULL,
    atualizado_em TIMESTAMP NOT NULL,
    CONSTRAINT uk_material_codigo UNIQUE (codigo),
    CONSTRAINT fk_material_localizacao FOREIGN KEY (localizacao_id) REFERENCES localizacao(id)
);

CREATE INDEX idx_material_localizacao ON material(localizacao_id);
CREATE INDEX idx_material_grupo ON material(grupo);
